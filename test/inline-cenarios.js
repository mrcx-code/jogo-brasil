// Build step (source-time only, never runs in the game): read the seven owner-painted scene
// data-URIs from assets/scenarios/cen1.webp .. cen7.webp and splice them into index.html
// between the CEN_FUNDO_B64 markers as the CENARIO_FUNDO_B64 array.
//
//   node test/inline-cenarios.js
//
// The .webp masters are SOURCE (like assets/hero/*.png): the shipped game stays one
// self-contained index.html with the paintings inlined, no runtime asset fetch.
const fs = require('fs');
const path = require('path');

const DIR = path.resolve(__dirname, '..', 'assets', 'scenarios');
// ALVO: src/jogo.ts, a FONTE. O index.html da raiz virou SAIDA do build na migracao para
// TypeScript — escrever nele funciona e some no proximo `npm run build`, sem erro nenhum.
const HTML = path.resolve(__dirname, '..', 'src', 'jogo.ts');

const NAMES = ['cen1', 'cen2', 'cen3', 'cen4', 'cen5', 'cen6', 'cen7'];
const parts = [];
let total = 0;
for (const n of NAMES) {
  // The masters are binary .webp now, not base64 text. Same bytes, a third less on disk:
  // base64 costs 33% and there was no reason to pay it twice — once here and once again in
  // the file this script writes into.
  const f = path.join(DIR, n + '.webp');
  if (!fs.existsSync(f)) {
    console.error('ERROR: falta ' + f);
    process.exit(1);
  }
  const s = 'data:image/webp;base64,' + fs.readFileSync(f).toString('base64');
  parts.push('  "' + s + '"');
  total += s.length;
  console.error(`${n}: ${(s.length / 1024).toFixed(1)}KB (base64)`);
}

const block = [
  '/*CEN_FUNDO_B64_START — generated by test/inline-cenarios.js, do not edit by hand*/',
  'const CENARIO_FUNDO_B64 = [',
  parts.join(',\n'),
  '];',
  '/*CEN_FUNDO_B64_END*/',
].join('\n');

let html = fs.readFileSync(HTML, 'utf8');
const re = /\/\*CEN_FUNDO_B64_START[\s\S]*?\/\*CEN_FUNDO_B64_END\*\//;
if (!re.test(html)) {
  console.error('ERROR: CEN_FUNDO_B64 markers not found in index.html — add the placeholder first.');
  process.exit(1);
}
html = html.replace(re, block);
fs.writeFileSync(HTML, html);
console.error(`\nInlined ${NAMES.length} scenes, ${(total / 1024).toFixed(1)}KB of base64, spliced into index.html.`);
